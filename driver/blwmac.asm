        align   4, db 0
blw_guid:                                       ; EC87D643-EBA4-4BB5-A1E5-3F3E36B20DA9: AMI's, already in
        dd      0xec87d643                      ; this firmware's GUID store. Creating a NEW vendor GUID
        dw      0xeba4, 0x4bb5                  ; hits an AMI bug that half-writes NVRAM (2026-11-08).
        db      0xa1, 0xe5, 0x3f, 0x3e, 0x36, 0xb2, 0x0d, 0xa9
loaded_image_guid:                              ; 5B1B31A1-9562-11D2-8E3F-00A0C969723B
        dd      0x5b1b31a1
        dw      0x9562, 0x11d2
        db      0x8e, 0x3f, 0x00, 0xa0, 0xc9, 0x69, 0x72, 0x3b
shell_if_guid:                                  ; 47C7B223-C42A-11D2-8E57-00A0C969723B
        dd      0x47c7b223
        dw      0xc42a, 0x11d2
        db      0x8e, 0x57, 0x00, 0xa0, 0xc9, 0x69, 0x72, 0x3b
smbios_guid:                                    ; EB9D2D31-2D88-11D3-9A16-0090273FC14D
        dd      0xeb9d2d31
        dw      0x2d88, 0x11d3
        db      0x9a, 0x16, 0x00, 0x90, 0x27, 0x3f, 0xc1, 0x4d
name_blwmac:
        dw      __utf16__('BlwMac'), 0
name_status:
        dw      __utf16__('BlwMacStatus'), 0
