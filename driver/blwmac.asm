; BlwMac: an EFI application (IA32) for the OpenFrame, run from boot.nsh:
;
;     fs1:\BlwMac.efi 00:0e:8e:12:34:56
;
; The OpenFrame's RTL8111C has no stored MAC address, so it powers up with junk in its MAC0
; registers; nor does the OpenFrame have a serial number of its own. This keeps one MAC in NVRAM,
; where BlwPlatformDxe (26.11.20 on) finds it on every boot. (Before 26.11.20 this was
; BlwLanMac.efi, storing the LAN MAC itself.) The MAC is either
;   - the WLAN card's own burned-in address (universally administered: bit 1 of the first octet
;     clear). The LAN MAC is made from it: 02 then its last five octets, as of-netplan makes it.
;     It also becomes the SMBIOS serial number and UUID. Any card's: a replacement card's address
;     is as much the hardware's as the original's; or
;   - a locally administered address (bit 1 set): the LAN MAC itself, generated by of-netplan when
;     there's no card. It goes into the NIC as it is and becomes the UUID, but not a serial
;     number, since it isn't the hardware's.
;
; 1. Finds the MAC (xx:xx:xx:xx:xx:xx or with '-') in the command line: LoadedImage->LoadOptions,
;    else the EDK1 shell's argv. Only the first is used. It must be unicast and not all zero.
; 2. If NVRAM variable BlwMac (under AMI's existing GUID EC87D643, NV+BS+RT, 6 bytes) already
;    holds it, nothing is written. Otherwise it first locks down flash blocks 1-15 (FWH
;    block-lock registers: write-lock + lock-down, cleared only by reset), so that nothing can
;    write the main firmware volume or the boot block until the next reset, then calls
;    SetVariable. This is the boot-services path the firmware itself uses for MonotonicCounter
;    on every boot. If the lock-down doesn't read back, nothing is written.
; 3. Reads BlwMac back and writes the LAN MAC into the NIC's MAC0 registers through its I/O BAR,
;    enabling I/O decode on the root port 00:1c.0 and the NIC for the duration and then
;    restoring both. It also fills in the SMBIOS table BlwPlatformDxe installed (smbios_id.inc):
;    the firmware read NVRAM at ReadyToBoot, before boot.nsh ran, so a MAC stored just now would
;    otherwise only reach SMBIOS next boot.
; 4. Records what it did in volatile variable BlwMacStatus (BS+RT, RAM only, 24 bytes): flags,
;    the SetVariable status, the MAC stored, the LAN MAC applied, 4 bytes pad. Linux can read it
;    with a read-only efivarfs.
;
; Always returns EFI_SUCCESS so boot.nsh carries on. Position-independent; assembled with
; `nasm -f bin`, wrapped as a PE32 application by build_blwmac_app.py.

bits 32

F_ARG_LOADOPT   equ 0x0001          ; MAC found in LoadOptions
F_ARG_SHELLIF   equ 0x0002          ; MAC found in the shell's argv
F_ARG_NONE      equ 0x0004          ; no usable MAC on the command line
F_HW_MAC        equ 0x0008          ; the stored MAC is a card's burned-in address
F_NV_SAME       equ 0x0010          ; NVRAM already held it: nothing written
F_NV_WRITTEN    equ 0x0020          ; SetVariable succeeded
F_NV_FAILED     equ 0x0040          ; SetVariable failed (status in the second dword)
F_LOCKDOWN_OK   equ 0x0080          ; blocks 1-15 locked down before the write
F_LOCKDOWN_BAD  equ 0x0100          ; lock-down didn't read back: nothing written
F_NV_READ_OK    equ 0x0200          ; BlwMac read back from NVRAM and usable
F_SMBIOS_DONE   equ 0x0400          ; SMBIOS UUID (and for a card, serial number) set
F_NIC_MISSING   equ 0x1000          ; no 10ec:8168 behind 00:1c.0, or no I/O BAR
F_NIC_DONE      equ 0x2000          ; MAC0 written and read back correctly
F_NIC_VERIFY    equ 0x4000          ; MAC0 read back wrong

FWH_LOCK        equ 0xFFB00002      ; block-lock register of block 0; block n is + n * 0x10000
NV_SIZE         equ 6               ; BlwMac: one MAC

; locals (ebp-relative)
L_STATUS        equ -40             ; 24 bytes: flags, SetVariable status, mac[6], lan[6], pad[4]
L_ARGMAC        equ -56             ; 16 bytes: the command line's MAC
L_NVMAC         equ -72             ; 16 bytes: what NVRAM holds
L_SIZE          equ -76
L_IFACE         equ -80
L_ATTR          equ -84
L_NARG          equ -88             ; MACs parsed into L_ARGMAC so far (0-1)
L_FRAME         equ 96

entry:
        push    ebp
        mov     ebp, esp
        sub     esp, L_FRAME
        push    ebx
        push    esi
        push    edi
        cld
        lea     edi, [ebp - L_FRAME]            ; zero the locals
        mov     ecx, L_FRAME / 4
        xor     eax, eax
        rep stosd
        call    .here
.here:  pop     ebx                             ; ebx = PIC base

; 1. the MAC on the command line
        mov     edi, F_ARG_LOADOPT
        call    arg_loadopts
        cmp     dword [ebp + L_NARG], 0
        jne     .parsed
        mov     edi, F_ARG_SHELLIF
        call    arg_shellif
        cmp     dword [ebp + L_NARG], 0
        jne     .parsed
.noarg: or      dword [ebp + L_STATUS], F_ARG_NONE
        jmp     .apply
.parsed:
        lea     esi, [ebp + L_ARGMAC]
        call    mac_ok
        test    eax, eax
        jz      .noarg
        or      [ebp + L_STATUS], edi

; 2. store it unless NVRAM already has it
        mov     dword [ebp + L_SIZE], 16
        lea     eax, [ebp + L_NVMAC]
        call    get_mac                         ; eax = status
        test    eax, eax
        jnz     .store
        cmp     dword [ebp + L_SIZE], NV_SIZE
        jne     .store
        lea     esi, [ebp + L_ARGMAC]
        lea     edi, [ebp + L_NVMAC]
        mov     ecx, NV_SIZE
        repe cmpsb
        jne     .store
        or      dword [ebp + L_STATUS], F_NV_SAME
        jmp     .apply

.store: call    lockdown                        ; eax = 0 when blocks 1-15 read back locked down
        test    eax, eax
        jz      .locked
        or      dword [ebp + L_STATUS], F_LOCKDOWN_BAD
        jmp     .apply
.locked:
        or      dword [ebp + L_STATUS], F_LOCKDOWN_OK
        lea     eax, [ebp + L_ARGMAC]
        push    eax                             ; Data
        push    NV_SIZE                         ; DataSize
        push    7                               ; NV | BS | RT
        lea     eax, [ebx + (blw_guid - entry.here)]
        push    eax
        lea     eax, [ebx + (name_blwmac - entry.here)]
        push    eax
        call    rt_setvariable
        add     esp, 20
        mov     [ebp + L_STATUS + 4], eax
        test    eax, eax
        jnz     .setfail
        or      dword [ebp + L_STATUS], F_NV_WRITTEN
        jmp     .apply
.setfail:
        or      dword [ebp + L_STATUS], F_NV_FAILED

; 3. program SMBIOS and the NIC from what NVRAM holds
.apply: mov     dword [ebp + L_SIZE], 16
        lea     eax, [ebp + L_NVMAC]
        call    get_mac
        test    eax, eax
        jnz     .report
        cmp     dword [ebp + L_SIZE], NV_SIZE
        jne     .report
        lea     esi, [ebp + L_NVMAC]
        call    mac_ok
        test    eax, eax
        jz      .report
        or      dword [ebp + L_STATUS], F_NV_READ_OK
        test    byte [ebp + L_NVMAC], 2
        jnz     .local
        or      dword [ebp + L_STATUS], F_HW_MAC
.local: lea     esi, [ebp + L_NVMAC]
        lea     edi, [ebp + L_STATUS + 8]
        movsd
        movsw
        call    find_smbios                     ; eax = SMBIOS entry point or 0
        test    eax, eax
        jz      .nic
        mov     esi, eax
        lea     edx, [ebp + L_NVMAC]
        call    smbios_set_id
        test    eax, eax
        jz      .nic
        or      dword [ebp + L_STATUS], F_SMBIOS_DONE
.nic:   lea     esi, [ebp + L_NVMAC]
        lea     edi, [ebp + L_STATUS + 14]
        call    lan_mac                         ; the LAN MAC, into the status
        lea     esi, [ebp + L_STATUS + 14]
        call    program_nic                     ; eax = flags to add
        or      [ebp + L_STATUS], eax

; 4. say what happened (volatile: RAM only, no flash write)
.report:
        lea     eax, [ebp + L_STATUS]
        push    eax
        push    24
        push    6                               ; BS | RT
        lea     eax, [ebx + (blw_guid - entry.here)]
        push    eax
        lea     eax, [ebx + (name_status - entry.here)]
        push    eax
        call    rt_setvariable
        add     esp, 20

        xor     eax, eax                        ; EFI_SUCCESS
        pop     edi
        pop     esi
        pop     ebx
        mov     esp, ebp
        pop     ebp
        ret

; ---------------------------------------------------------------------------------------------
; RT->SetVariable(Name, Guid, Attributes, DataSize, Data), arguments already pushed by the caller
; below our return address. Returns its status in eax.
rt_setvariable:
        mov     eax, [ebp + 12]                 ; SystemTable
        mov     eax, [eax + 0x38]               ; ->RuntimeServices
        jmp     [eax + 0x38]                    ; SetVariable (tail call: same arguments)

; get_mac: eax = buffer, [ebp+L_SIZE] = its size. GetVariable(BlwMac). Returns status.
get_mac:
        push    eax                             ; Data
        lea     ecx, [ebp + L_SIZE]
        push    ecx                             ; &DataSize
        lea     ecx, [ebp + L_ATTR]
        push    ecx                             ; &Attributes
        lea     ecx, [ebx + (blw_guid - entry.here)]
        push    ecx
        lea     ecx, [ebx + (name_blwmac - entry.here)]
        push    ecx
        mov     eax, [ebp + 12]
        mov     eax, [eax + 0x38]
        call    [eax + 0x30]                    ; RT->GetVariable
        add     esp, 20
        ret

; find_smbios: eax = the SMBIOS entry point in the system's configuration table, or 0.
; Keeps ebx, esi, edi.
find_smbios:
        push    esi
        push    edi
        mov     eax, [ebp + 12]
        mov     edx, [eax + 0x40]               ; ST->NumberOfTableEntries
        mov     eax, [eax + 0x44]               ; ST->ConfigurationTable (GUID + pointer, 20 bytes)
.scan:  test    edx, edx
        jz      .none
        lea     esi, [ebx + (smbios_guid - entry.here)]
        mov     edi, eax
        mov     ecx, 4
        repe cmpsd
        je      .found
        add     eax, 20
        dec     edx
        jmp     .scan
.found: mov     eax, [eax + 16]
        jmp     .out
.none:  xor     eax, eax
.out:   pop     edi
        pop     esi
        ret

; arg_loadopts: parse the MAC in LoadedImage->LoadOptions into L_ARGMAC. Keeps ebx, edi.
arg_loadopts:
        push    edi
        lea     eax, [ebx + (loaded_image_guid - entry.here)]
        call    handle_protocol                 ; eax = interface or 0
        test    eax, eax
        jz      .out
        mov     esi, [eax + 0x1c]               ; LoadOptions
        mov     ecx, [eax + 0x18]               ; LoadOptionsSize (bytes)
        shr     ecx, 1
        test    esi, esi
        jz      .out
        cmp     ecx, 1024                       ; a command line, not a runaway size
        jbe     .scan
        mov     ecx, 1024
.scan:  call    find_macs
.out:   pop     edi
        ret

; arg_shellif: parse the MAC in the EDK1 shell interface's Argv[1..] into L_ARGMAC. Keeps ebx, edi.
arg_shellif:
        push    edi
        lea     eax, [ebx + (shell_if_guid - entry.here)]
        call    handle_protocol
        test    eax, eax
        jz      .out
        mov     edi, [eax + 8]                  ; Argv
        mov     edx, [eax + 12]                 ; Argc
        test    edi, edi
        jz      .out
        cmp     edx, 64
        ja      .out
        mov     eax, 1
.arg:   cmp     eax, edx
        jae     .out
        push    eax
        push    edx
        mov     esi, [edi + eax * 4]
        test    esi, esi
        jz      .next
        xor     ecx, ecx                        ; ecx = wcslen, at most 256
.len:   cmp     word [esi + ecx * 2], 0
        je      .gotlen
        inc     ecx
        cmp     ecx, 256
        jb      .len
.gotlen:
        call    find_macs
.next:  pop     edx
        pop     eax
        inc     eax
        jmp     .arg
.out:   pop     edi
        ret

; handle_protocol: eax = &Guid. BS->HandleProtocol(ImageHandle, Guid, &Interface). eax = Interface or 0.
handle_protocol:
        mov     dword [ebp + L_IFACE], 0
        lea     ecx, [ebp + L_IFACE]
        push    ecx
        push    eax
        push    dword [ebp + 8]                 ; ImageHandle
        mov     eax, [ebp + 12]
        mov     eax, [eax + 0x3c]               ; BootServices
        call    [eax + 0x58]                    ; HandleProtocol
        add     esp, 12
        test    eax, eax
        jnz     .no
        mov     eax, [ebp + L_IFACE]
        ret
.no:    xor     eax, eax
        ret

; find_macs: esi = CHAR16 string, ecx = length in characters. Parses the first xx:xx:xx:xx:xx:xx
; (':' or '-') into L_ARGMAC and counts it in L_NARG; once there is one, it stops looking.
; Whether it's usable is checked afterwards. Keeps ebx, esi, edi.
find_macs:
        push    esi
        push    edi
.pos:   cmp     dword [ebp + L_NARG], 1
        jae     .out
        cmp     ecx, 17
        jb      .out
        push    ecx
        push    esi
        mov     edi, [ebp + L_NARG]
        imul    edi, edi, 6
        lea     edi, [ebp + L_ARGMAC + edi]
        xor     edx, edx                        ; octet index
.oct:   movzx   eax, word [esi]                 ; (ecx is saved on the stack, so cl is free)
        call    hexval
        jc      .fail
        shl     al, 4
        mov     cl, al                          ; high nibble
        movzx   eax, word [esi + 2]
        call    hexval
        jc      .fail
        or      al, cl
        mov     [edi + edx], al
        inc     edx
        cmp     edx, 6
        je      .parsed
        movzx   eax, word [esi + 4]
        cmp     eax, ':'
        je      .sep
        cmp     eax, '-'
        jne     .fail
.sep:   add     esi, 6
        jmp     .oct
.parsed:
        pop     esi
        pop     ecx
        inc     dword [ebp + L_NARG]
        add     esi, 34                         ; past it
        sub     ecx, 17
        jmp     .pos
.fail:  pop     esi
        pop     ecx
        add     esi, 2
        dec     ecx
        jmp     .pos
.out:   pop     edi
        pop     esi
        ret

; hexval: eax = character. al = value with CF clear, or CF set if not a hex digit. Keeps ecx.
hexval: cmp     eax, '0'
        jb      .bad
        cmp     eax, '9'
        jbe     .dig
        or      eax, 0x20                       ; lower case
        cmp     eax, 'a'
        jb      .bad
        cmp     eax, 'f'
        ja      .bad
        sub     eax, 'a' - 10
        clc
        ret
.dig:   sub     eax, '0'
        clc
        ret
.bad:   stc
        ret

; mac_ok: esi = 6 bytes. eax = 1 if unicast and not all zero. Keeps esi; clobbers ecx, edx.
mac_ok: xor     eax, eax
        test    byte [esi], 1                   ; multicast bit
        jnz     .r
        mov     ecx, [esi]
        movzx   edx, word [esi + 4]
        or      ecx, edx
        jz      .r
        mov     eax, 1
.r:     ret

; lockdown: write-lock + lock-down (0x03) flash blocks 1-15 and read them back.
; eax = 0 if every one reads back with both bits set, else 1. Never touches block 0 (NVRAM) or
; the flash data space.
lockdown:
        mov     edx, FWH_LOCK + 0x10000         ; block 1
        mov     ecx, 15
.blk:   mov     byte [edx], 0x03
        mov     al, [edx]
        and     al, 0x03
        cmp     al, 0x03
        jne     .bad
        add     edx, 0x10000
        dec     ecx
        jnz     .blk
        xor     eax, eax
        ret
.bad:   mov     eax, 1
        ret

