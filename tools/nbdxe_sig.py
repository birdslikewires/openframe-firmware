"""Writes driver/nbdxe_sig.inc: the byte signature by which panel_clock.inc recognises, in memory,
the stock north-bridge driver's function that writes the fixed LVDS clock (NBDXE, FFS file
E4ECD0B2-E277-4F2B-BECB-E4D75C9A812E, every OF1 build), so it can change the value it writes.

    venv/bin/python -I tools/nbdxe_sig.py releases/of1-blw-26.11.23.bin driver/nbdxe_sig.inc

The function (RVA 0x3ca) reads the graphics device's BAR0, unlocks PP_CONTROL, does
mov dword [edx+0x6018], 0xd8027203 (DPLL_B) and locks PP_CONTROL again. The signature is the
whole function less the dwords the PE relocations patch, as (offset, length, bytes) runs ended by a
zero length (mmc_sig.inc's format, checked by mmc_sig_match). It includes the value itself, so only
the exact stock instruction ever matches.
"""
import sys
import uefi_firmware
import pefile
sys.path.insert(0, __file__.rsplit('/', 1)[0])
from mmc_sig import find_pe  # noqa: E402

NBDXE = 'e4ecd0b2-e277-4f2b-becb-e4d75c9a812e'
FN, END = 0x3ca, 0x40a                                  # the function, up to and including leave; ret
INSN = bytes.fromhex('c78218600000') + (0xd8027203).to_bytes(4, 'little')   # mov dword [edx+0x6018], 0xd8027203
INSN_RVA = 0x3fc


def main():
    img, out = sys.argv[1], sys.argv[2]
    pe = pefile.PE(data=find_pe(uefi_firmware.AutoParser(open(img, 'rb').read()).parse(), NBDXE))
    mem = pe.get_memory_mapped_image()
    code = mem[FN:END]
    assert code.startswith(bytes.fromhex('558bec')) and code.endswith(bytes.fromhex('c9c3')), 'unexpected function bounds'
    assert mem[INSN_RVA:INSN_RVA + 10] == INSN, 'DPLL_B write not where expected'
    relocs = sorted(e.rva for b in pe.DIRECTORY_ENTRY_BASERELOC for e in b.entries if e.type == 3)
    masked = [r - FN for r in relocs if FN <= r < END]
    assert not any(INSN_RVA - FN <= m < INSN_RVA - FN + 10 for m in masked), 'the write itself is relocated'
    runs, pos = [], 0
    for m in masked + [len(code)]:
        if m > pos:
            runs.append((pos, code[pos:m]))
        pos = m + 4
    with open(out, 'w') as f:
        f.write('; Generated by tools/nbdxe_sig.py from %s: do not edit.\n' % img.split('/')[-1])
        f.write('; NBDXE (%s) clock write: RVA 0x%x-0x%x, relocated dwords at +%s.\n'
                % (NBDXE.upper(), FN, END, ', +'.join('0x%x' % m for m in masked)))
        f.write('NBD_FN_RVA      equ     0x%x\n' % FN)
        f.write('NBD_IMM_RVA     equ     0x%x                     ; the imm32 of the DPLL_B write\n' % (INSN_RVA + 6))
        f.write('NBD_END_RVA     equ     0x%x\n' % END)
        f.write('nbd_sig:\n')
        for off, data in runs:
            f.write('        dw      0x%04x, 0x%04x\n' % (off, len(data)))
            for i in range(0, len(data), 16):
                f.write('        db      ' + ', '.join('0x%02x' % b for b in data[i:i + 16]) + '\n')
        f.write('        dw      0, 0\n')
    print('NBDXE clock write 0x%x-0x%x, %d runs, masked %s' % (FN, END, len(runs), masked))


if __name__ == '__main__':
    main()
