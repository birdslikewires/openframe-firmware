"""Writes driver/ceata_sig.inc: the byte signature by which ceata.inc recognises, in memory, the
stock MMC/SD media driver's CE-ATA check (MmcMediaDevice, FFS file DD223EF8-6D1B-490A-A53E-
BA86FAAEB778, every OF1 build), so it can make it answer "not CE-ATA" at once.

    venv/bin/python -I tools/ceata_sig.py releases/of1-blw-26.11.24.bin driver/ceata_sig.inc

The check (RVA 0x72b) reads 16 CE-ATA registers with CMD60 (RW_MULTIPLE_REGISTER, through the
helper at RVA 0x260, with a 5000-poll timeout) and looks for the CE-ATA signature CE AA. No MMC
answers CMD60: on an OF1 the command waits 2.8 s, every boot, before the driver resets the host
and carries on with the card as MMC. Start calls it only for a card already identified as MMC
(card type 1), and would switch to its CE-ATA path (type 2) on a match. The generator checks all
of that, and that nothing in the function is relocated (the signature is then its exact bytes,
in mmc_sig.inc's run format for mmc_sig_match).
"""
import struct
import sys
import uefi_firmware
import pefile
sys.path.insert(0, __file__.rsplit('/', 1)[0])
from mmc_sig import find_pe, MMC_GUID  # noqa: E402

FN, END = 0x72b, 0x77a                                  # the check, up to and including its last ret
HELPER = 0x260                                          # the CMD60 helper it calls
CALLER = 0xdea                                          # Start's call of it


def main():
    img, out = sys.argv[1], sys.argv[2]
    pe = pefile.PE(data=find_pe(uefi_firmware.AutoParser(open(img, 'rb').read()).parse(), MMC_GUID))
    mem = pe.get_memory_mapped_image()
    code = mem[FN:END]
    assert code.startswith(bytes.fromhex('568b742408')) and code.endswith(bytes.fromhex('b0015ec3')), 'unexpected function bounds'
    # It calls the CMD60 helper (call rel32 at +0x13) and checks for CE AA in the reply.
    assert code[0x13] == 0xe8 and FN + 0x18 + struct.unpack_from('<i', code, 0x14)[0] == HELPER, 'not the CMD60 helper'
    assert bytes.fromhex('80beac020000ce') in code and bytes.fromhex('80bead020000aa') in code, 'no CE AA check'
    helper = mem[HELPER:HELPER + 0xd2]
    assert helper.count(bytes.fromhex('6a3c')) == 2 and helper.count(bytes.fromhex('6888130000')) == 2, 'helper is not CMD60 with timeout 5000'
    # Start: cmp dword [esi+0x50], 1 ... push esi; call FN
    assert mem[CALLER - 10:CALLER - 6] == bytes.fromhex('837e5001'), 'caller does not test for an MMC card'
    assert mem[CALLER] == 0xe8 and CALLER + 5 + struct.unpack_from('<i', mem, CALLER + 1)[0] == FN, 'caller does not call the check'
    relocs = sorted(e.rva for b in pe.DIRECTORY_ENTRY_BASERELOC for e in b.entries if e.type == 3)
    masked = [r - FN for r in relocs if FN - 3 <= r < END]
    assert not masked, 'relocated dwords in the check: %s' % masked
    with open(out, 'w') as f:
        f.write('; Generated by tools/ceata_sig.py from %s: do not edit.\n' % img.split('/')[-1])
        f.write('; MmcMediaDevice (%s) CE-ATA check: RVA 0x%x-0x%x, nothing relocated.\n' % (MMC_GUID.upper(), FN, END))
        f.write('CEA_FN_RVA      equ     0x%x\n' % FN)
        f.write('CEA_END_RVA     equ     0x%x\n' % END)
        f.write('cea_sig:\n')
        f.write('        dw      0x0000, 0x%04x\n' % len(code))
        for i in range(0, len(code), 16):
            f.write('        db      ' + ', '.join('0x%02x' % b for b in code[i:i + 16]) + '\n')
        f.write('        dw      0, 0\n')
    print('CE-ATA check 0x%x-0x%x (%d bytes), helper 0x%x, called from 0x%x' % (FN, END, len(code), HELPER, CALLER))


if __name__ == '__main__':
    main()
