"""Writes driver/mmc_sig.inc: the byte signatures by which mmc_fix.inc recognises the firmware's
MMC/SD media driver's BlockIo ReadBlocks and WriteBlocks (MmcMediaDevice, FFS file
DD223EF8-6D1B-490A-A53E-BA86FAAEB778, in every OF1 build), whose split transfers don't advance
the card address past the second 512 KB chunk (see mmc_fix.inc).

    venv/bin/python -I tools/mmc_sig.py releases/of1-blw-26.11.21.bin driver/mmc_sig.inc

Each signature is the whole function, less the dwords the PE relocations patch (absolute
addresses, which depend on where the core loaded the driver): a table of (offset, length, bytes)
runs, ended by a zero length. The function addresses are the BlockIo template's, found from the
code that fills it in, and checked against the expected prologue and the bug itself.
"""
import struct
import sys
import uefi_firmware
import pefile

MMC_GUID = 'dd223ef8-6d1b-490a-a53e-ba86faaeb778'


def find_pe(obj):
    stack = [obj]
    while stack:
        o = stack.pop()
        if type(o).__name__ == 'FirmwareFile' and o.guid_label == MMC_GUID:
            pes = []
            todo = [o]
            while todo:
                x = todo.pop()
                if type(x).__name__ == 'FirmwareFileSystemSection' and x.type == 0x10:
                    pes.append(x.data)
                todo.extend(getattr(x, 'objects', []) or [])
            assert len(pes) == 1, 'expected one PE32 section in MmcMediaDevice'
            return pes[0]
        stack.extend(getattr(o, 'objects', []) or [])
    raise SystemExit('MmcMediaDevice (%s) not found' % MMC_GUID)


def main():
    img, out = sys.argv[1], sys.argv[2]
    fw = uefi_firmware.AutoParser(open(img, 'rb').read()).parse()
    pe_bytes = find_pe(fw)
    pe = pefile.PE(data=pe_bytes)
    mem = pe.get_memory_mapped_image()
    base = pe.OPTIONAL_HEADER.ImageBase
    relocs = sorted(e.rva for b in pe.DIRECTORY_ENTRY_BASERELOC for e in b.entries if e.type == 3)

    # The BlockIo template: mov dword [eax+0x14..0x20], Reset/ReadBlocks/WriteBlocks/FlushBlocks.
    pat = bytes.fromhex('c74014')
    at = mem.find(pat)
    while at >= 0 and not (mem[at + 7:at + 10] == bytes.fromhex('c74018') and mem[at + 14:at + 17] == bytes.fromhex('c7401c')):
        at = mem.find(pat, at + 1)
    assert at >= 0, 'BlockIo template not found'
    read = struct.unpack_from('<I', mem, at + 10)[0] - base
    write = struct.unpack_from('<I', mem, at + 17)[0] - base

    def extent(start):
        # Up to and including the function's final 'leave; ret' (c9 c3) before the next function.
        end = mem.find(b'\xc9\xc3', start)
        assert end > start
        return end + 2

    funcs = []
    for name, start in (('read', read), ('write', write)):
        end = extent(start)
        code = mem[start:end]
        assert code.startswith(bytes.fromhex('558bec')), name + ': unexpected prologue'
        # The bug: each chunk's address is recomputed as BlockSize * the caller's LBA plus this
        # chunk's length (imul reg, [ebp+0x10] in the loop, which never updates the LBA).
        assert code.count(bytes.fromhex('0faf4d10')) + code.count(bytes.fromhex('0faf7d10')) >= 2, name + ': bug pattern not found'
        masked = [r - start for r in relocs if start <= r < end]
        runs, pos = [], 0
        for m in masked + [len(code)]:
            if m > pos:
                runs.append((pos, code[pos:m]))
            pos = m + 4
        funcs.append((name, start, end, masked, runs))

    with open(out, 'w') as f:
        f.write('; Generated by tools/mmc_sig.py from %s: do not edit.\n' % img.split('/')[-1])
        f.write('; MmcMediaDevice (%s) BlockIo functions, less their relocated dwords.\n' % MMC_GUID.upper())
        for name, start, end, masked, runs in funcs:
            f.write('\n; %sBlocks: RVA 0x%x-0x%x (0x%x bytes), relocated dwords at +%s\n'
                    % (name.capitalize(), start, end, end - start, ', +'.join('0x%x' % m for m in masked)))
            f.write('mmc_sig_%s:\n' % name)
            for off, data in runs:
                f.write('        dw      0x%04x, 0x%04x\n' % (off, len(data)))
                for i in range(0, len(data), 16):
                    f.write('        db      ' + ', '.join('0x%02x' % b for b in data[i:i + 16]) + '\n')
            f.write('        dw      0, 0\n')
    for name, start, end, masked, runs in funcs:
        print('%sBlocks RVA 0x%x-0x%x, %d runs, masked %s' % (name, start, end, len(runs), masked))


if __name__ == '__main__':
    main()
