"""Writes driver/usbrt_sig.inc: the byte signature by which usbrt.inc recognises, in memory, the
firmware USB code's StartUnit function (USBRT, FFS file 04EAAAA1-29A1-11D7-8838-00500473D4EB, the
OF1 builds), so the mass-storage identify step can call it to wake a sleeping drive.

    venv/bin/python -I tools/usbrt_sig.py releases/of1-blw-26.11.26.bin driver/usbrt_sig.inc

StartUnit (RVA 0x4e84) takes the device: unless the device has flag 0x20 at +0x45, it sends SCSI
START STOP UNIT (opcode 0x1b, CDB byte 4 = 1: start) with a 10 s timeout, then REQUEST SENSE
(RVA 0x4c61), and returns that sense code. The signature is the whole function less the dwords
the PE relocations patch, as (offset, length, bytes) runs ended by a zero length (mmc_sig.inc's
format, checked by mmc_sig_match). The generator checks the opcode, the start bit, the timeout and
the calls, so a different function never matches.
"""
import struct
import sys
import uefi_firmware
import pefile
sys.path.insert(0, __file__.rsplit('/', 1)[0])
from mmc_sig import find_pe  # noqa: E402

USBRT = '04eaaaa1-29a1-11d7-8838-00500473d4eb'
FN, END = 0x4e84, 0x4ef4                                # StartUnit, up to and including its ret
SENSE = 0x4c61                                          # its REQUEST SENSE call's target


def main():
    img, out = sys.argv[1], sys.argv[2]
    pe = pefile.PE(data=find_pe(uefi_firmware.AutoParser(open(img, 'rb').read()).parse(), USBRT))
    mem = pe.get_memory_mapped_image()
    code = mem[FN:END]
    assert code.startswith(bytes.fromhex('578b7c2408f6474520')) and code.endswith(bytes.fromhex('5e5fc3')), 'unexpected bounds'
    assert bytes.fromhex('c6061bc6460401') in code, 'not START STOP UNIT (start)'
    assert bytes.fromhex('66c780e40d00001027') in code, 'not the 10 s timeout'
    at = code.index(bytes.fromhex('57e8')) + 1            # push edi; call REQUEST SENSE
    assert FN + at + 5 + struct.unpack_from('<i', code, at + 1)[0] == SENSE, 'does not end with REQUEST SENSE'
    relocs = sorted(e.rva for b in pe.DIRECTORY_ENTRY_BASERELOC for e in b.entries if e.type == 3)
    masked = [r - FN for r in relocs if FN <= r < END]
    runs, pos = [], 0
    for m in masked + [len(code)]:
        if m > pos:
            runs.append((pos, code[pos:m]))
        pos = m + 4
    with open(out, 'w') as f:
        f.write('; Generated by tools/usbrt_sig.py from %s: do not edit.\n' % img.split('/')[-1])
        f.write('; USBRT (%s) StartUnit: RVA 0x%x-0x%x, relocated dwords at +%s.\n'
                % (USBRT.upper(), FN, END, ', +'.join('0x%x' % m for m in masked)))
        f.write('URT_START_RVA   equ     0x%x\n' % FN)
        f.write('urt_sig_start:\n')
        for off, data in runs:
            f.write('        dw      0x%04x, 0x%04x\n' % (off, len(data)))
            for i in range(0, len(data), 16):
                f.write('        db      ' + ', '.join('0x%02x' % b for b in data[i:i + 16]) + '\n')
        f.write('        dw      0, 0\n')
    print('StartUnit 0x%x-0x%x, %d runs, masked %s' % (FN, END, len(runs), masked))


if __name__ == '__main__':
    main()
